#pragma once
// ===========================================================================
// Effects/OnHitResolution.h
// -------------------------
// 役割:
//   OnHitフェーズ(着弾時)の解決結果。壁命中・敵命中の双方から共通で使う。
//   各 <Name>OnHit ハンドラがここへ積み、命中System が結果を見て弾の生死や
//   挙動(貫通/反射)を決める。
//
// 責務:
//   - 着弾時に弾がどう振る舞うか(貫通・反射)のフラグ集約のみ。
//
// アーキテクチャ上の位置付け:
//   BulletWallCollisionSystem(壁) と BulletEnemyCollisionSystem(敵) の双方が
//   ResolveOnHit で本構造体を得て、pierce/reflect を見て処理を分岐する。
//   「壁に対する反射」は敵には無関係など、使う側が必要なフラグだけ参照する。
//
// 設計方針:
//   - Spawn/Travel と同じ「ハンドラ→Resolution集約」の思想。ただし OnHit は
//     数値合成より「貫通か否か」等のフラグ判定が主なので bool 集約とする。
//   - 貫通(pierce)は「当たっても消えない・通過する」を意味する共通概念。壁では
//     「壁をすり抜ける」、敵では「敵を貫いて飛び続ける」として解釈される。
// ===========================================================================

struct OnHitResolution
{
    bool pierce = false; ///< 貫通する(着弾しても消えず通過する)。Focus が立てる。
    bool reflect = false; ///< 反射する(壁で跳ね返る)。Reflection が立てる。敵命中では未使用。
};