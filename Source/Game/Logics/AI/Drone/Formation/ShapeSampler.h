#pragma once
// ===========================================================================
// 概要: モデルの表面から、ドローンを並べる点を取り出す（モデル陣形の形の元）。
//
// 責務:
//   - モデルの三角形を、描画と同じ姿勢（ノードの初期姿勢を掛けた位置）で集める
//   - 面積に比例して表面に点を落とす
//   - 最遠点サンプリングで、先頭から何個取っても形全体に散らばる順に並べる
//
// 備考:
//   並び順がこの処理の要。ドローンは撃破で減るので、生き残りの機数ぶんだけ先頭から使う。
//   最遠点の順なら、半分に減っても形が欠けずに粗くなるだけで済む。
//   ランダムな順だと、減ったときに偶然どこかが抜けて形が読めなくなる。
//
//   乱数の種を固定している。同じモデルからは毎回同じ点が出るので、当たり方を再現して調整できる。
// ===========================================================================
#include <string>
#include <vector>

#include "SimpleMath.h"

namespace CCL::AI::Formation
{
    // modelPath のモデルの表面から maxPoints 個の点を取り出し、最遠点の順に並べて返す。
    // 座標はモデル空間。読めなかった・三角形が無かったときは空を返す。
    //
    // 読み込みと並べ替えに時間がかかる（数千点 × 数千点の距離計算）ので、陣形の登録時に1回だけ呼ぶ。
    std::vector<DirectX::SimpleMath::Vector3> SampleModelSurface(const std::string &modelPath, int maxPoints);

} // namespace CCL::AI::Formation
