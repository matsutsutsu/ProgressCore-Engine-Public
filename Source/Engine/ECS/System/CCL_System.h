#pragma once
// ===========================================================================
// CCL_System.h
// ------------
// 【集約ヘッダ / Umbrella Header】
//
// このファイル自体には実装を持たず、System レイヤーを構成する複数の個別
// ヘッダをまとめて include するだけのファイルです。
//
// これにより:
//   - 既存コード（`#include "CCL_System.h"`）は何も変更せずビルドが通る
//   - 新規コードは必要なヘッダだけを個別 include することでビルド速度UP
//
// という双方の利点を両立できます。
//
// ---------------------------------------------------------------------------
// 構成（責務分割）
// ---------------------------------------------------------------------------
//   CCL_SystemAccess.h  : Read<T> / Write<T> アクセス指定子
//   CCL_SystemBase.h    : SystemBase 仮想インターフェース（軽量）
//   CCL_IfSystem.h      : IfSystem<> テンプレート本体（ForEach 系含む・重め）
//
// ---------------------------------------------------------------------------
// 推奨: System 派生クラスを実装する場合は本ヘッダか CCL_IfSystem.h を、
//       SystemManager や TaskScheduler 等のフレームワーク内部で「System を
//       格納する側」のコードは CCL_SystemBase.h のみを include すると
//       ビルド時間に有利です。
// ===========================================================================

#include "CCL_SystemAccess.h"
#include "CCL_SystemBase.h"
#include "CCL_IfSystem.h"
