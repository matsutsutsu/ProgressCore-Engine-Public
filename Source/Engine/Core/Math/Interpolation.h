// Interpolation.h
// ---------------
// 役割:
//   補間まわりで「知らないと必ず間違える」式だけを、理由付きで1箇所に置く。
//
// 何を置かないか（重要）:
//   - 線形補間は std::lerp / SimpleMath::Vector3::Lerp を使う。自前で書かない。
//   - クランプは std::clamp。
//   - デザイナが調整したいイージングは関数ではなくカーブに寄せる（CurveData.h）。
//     ここに EaseInBounce のような固定関数を並べるとカーブエディタと役割が競合し、
//     「使われない関数の置き場」になる。
//   ※ 短いから共通化するのではなく、間違えやすいから共通化する。
//     この基準を外すと、全システムが include する巨大ヘッダになって
//     1行の変更が毎回フルリビルドを呼ぶ。
// ===========================================================================
#include <cmath>

namespace CCL::Math
{

    /// @brief フレームレート非依存の追従係数。std::lerp(現在値, 目標値, Damp(speed, dt)) の形で使う。
    /// @param speed 1秒あたりの追従の速さ。大きいほど速く目標へ着く。
    /// @param dt    経過時間(秒)。
    /// @return 0..1 の補間係数。
    /// @note  素直に lerp(現在値, 目標値, speed * dt) と書くと、係数がフレーム時間に
    ///        比例してしまい、60fps と 144fps で追従速度が変わる。指数で書くと
    ///        「1秒あたりに残る割合」が固定されるため、可変フレームレートでも同じ動きになる。
    ///        カメラの追従・HPバーの遅れ表示など、ダンピングは必ずこれを通すこと。
    inline float Damp(float speed, float dt)
    {
        return 1.0f - std::exp(-speed * dt);
    }
    
    /// @brief 0..1 を S 字に整形する（両端で速度 0）。
    /// @note  1階微分までが連続。線形のままだと開始と終了が唐突に見える演出に使う。
    inline float SmoothStep(float t)
    {
        if (t <= 0.0f) return 0.0f;
        if (t >= 1.0f) return 1.0f;
        return t * t * (3.0f - 2.0f * t);
    }
    
    /// @brief 0..1 を S 字に整形する（両端で加速度まで 0）。
    /// @note  2階微分までが連続なのが SmoothStep との違い。区間をまたぐ瞬間に
    ///        加速度が折れないので、ノイズの格子補間のように「境目が周期的な
    ///        カクつきとして見えてしまう」用途はこちらを使う。
    inline float SmootherStep(float t)
    {
        if (t <= 0.0f) return 0.0f;
        if (t >= 1.0f) return 1.0f;
        return t * t * t * (t * (t * 6.0f - 15.0f) + 10.0f);
    }

} // namespace CCL::Math
