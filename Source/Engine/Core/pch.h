#pragma once
// ===========================================================================
// pch.h - Precompiled Header
// ===========================================================================
//
// 【目的】
//   全 .cpp で頻繁に使われる「重い」「変更頻度の低い」ヘッダを事前コンパイル
//   しておくことで、プロジェクト全体のビルド時間を 10〜30% 短縮します。
//
// 【適用方式】
//   強制インクルード方式 (/FI pch.h)。
//   各 .cpp に `#include "pch.h"` を書く必要はなく、VS2022 のプロジェクト
//   設定で自動的に先頭に挿入されます。
//
// 【含めて良いもの】
//   ✅ 標準ライブラリ（変更されない）
//   ✅ Windows / DirectX（巨大で頻繁に include される）
//   ✅ 安定したサードパーティライブラリ
//
// 【含めてはいけないもの】
//   ❌ 自作ヘッダ（変更されると全体再ビルドになる）
//   ❌ 特定の .cpp でしか使わないヘッダ（オーバーヘッドが残る）
//   ❌ #define による挙動切替え系（Tracy 等）
//
// 【メンテナンスルール】
//   - pch.h に新しいヘッダを追加する前に「本当に過半数の .cpp で使われるか」
//     を必ず確認すること。
//   - 自作ヘッダの追加は原則禁止（販売エンジンの保守性を守るため）。
// ===========================================================================


// ===========================================================================
// 1. プラットフォーム・マクロ設定
// ---------------------------------------------------------------------------
// Windows.h を include する前に、不要な機能を無効化するマクロを定義します。
// この順序を間違えるとマクロが効かなくなるため、必ずファイル冒頭に置きます。
// ===========================================================================

/// @brief 不要な Windows API（ネットワーク・コマンドライン引数解析等）を除外
///        →ビルド速度向上、シンボル衝突防止
#ifndef WIN32_LEAN_AND_MEAN
#define WIN32_LEAN_AND_MEAN
#endif

/// @brief Windows.h が定義する min/max マクロを無効化
///        →std::min / std::max / (std::min)() 構文との衝突防止
///        ※絶対必須。これが無いと至る所でビルドエラーが発生する。
#ifndef NOMINMAX
#define NOMINMAX
#endif

/// @brief Windows ヘッダの軽量化（コンソール系の不要ヘッダを除外）
#ifndef VC_EXTRALEAN
#define VC_EXTRALEAN
#endif


// ===========================================================================
// 2. Windows / DirectX 11
// ---------------------------------------------------------------------------
// 1つ1つが巨大なため、PCH に入れる効果が最も大きい区画です。
// ===========================================================================

#include <Windows.h>
#include <windowsx.h>     // GET_X_LPARAM / GET_Y_LPARAM 等のマクロ

// --- DirectX 11 系 ---
#include <d3d11.h>
#include <d3dcompiler.h>
#include <DirectXMath.h>
#include <DirectXColors.h>

// --- Microsoft::WRL::ComPtr（COM オブジェクトのスマートポインタ） ---
#include <wrl/client.h>

// COM オブジェクト解放用の小ユーティリティ（プロジェクト全体で使い回し可）
// 例: SafeRelease(_pDevice);
#ifndef SAFE_RELEASE
#define SAFE_RELEASE(p) do { if (p) { (p)->Release(); (p) = nullptr; } } while(0)
#endif


