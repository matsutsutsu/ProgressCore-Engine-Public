// ===========================================================================
// 注意事項（メンテナンスメモ）
// ---------------------------------------------------------------------------
//
// 1) 【ヘッダ追加時のチェックリスト】
//    □ 本当に過半数の .cpp で使われるか？
//    □ 変更頻度は十分に低いか？（少なくとも月単位で変わらない）
//    □ #define で挙動が変わるヘッダではないか？（Tracy / TRACY_ENABLE 等）
//
// 2) 【ECS / 自作ヘッダの追加は禁止】
//    自作ヘッダを追加すると、そのヘッダ変更時に全 .cpp が再ビルドされる
//    地獄が始まります。Step 1〜4 で分割した意味が消えてしまうため、
//    PCH には絶対に追加しないこと。
//
// 3) 【ビルドエラー対処】
//    NOMINMAX が効かない場合：
//      → 他のヘッダ（例: gdiplus.h）が pch.h より先に Windows.h を
//        include していないかチェック。pch.h は必ず最初に include される
//        ように /FI で強制 include していること。
//
//    min/max のシンボル衝突が起きる場合：
//      → コード側で `(std::min)(a, b)` のように丸括弧で囲むことで
//        マクロ展開を回避できます。
//
// 4) 【効果計測の推奨】
//    PCH 導入前後で「リビルド時間」を計測してください。
//      - 計測コマンド: Visual Studio → ビルド → ソリューションのリビルド
//      - 出力ウィンドウ末尾に "経過時間" が表示されます
//    効果が薄い場合は、含めているヘッダの選定を見直す指針になります。
//
// ===========================================================================
