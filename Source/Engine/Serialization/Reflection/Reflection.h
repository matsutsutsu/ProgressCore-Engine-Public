// =====================================================================
// Reflection.h
//   コード生成ツール (ccl_codegen.py) が読み取るアノテーションマクロ群。
//
//   重要:
//     これらのマクロはすべて「空」に展開される。
//     コンパイラから見るとコメントと変わらない。
//     ccl_codegen.py が正規表現でこれらを抽出してメタ情報を生成する。
//
//   なぜマクロにするのか:
//     - コードフォーマッタ (clang-format) が壊さない
//     - エディタ上でも目立つので「メタ情報がここにある」と読める
//     - IntelliSense がノイズと認識しない
//
//   設計上の制約:
//     - 1 つの CCL_FIELD 注釈は、直後の 1 行 (フィールド宣言) に作用する
//     - アノテーションは「ヘッダで宣言した型」にしか効かない
//     - .cpp で前方宣言だけの型はパース対象外
// =====================================================================
#pragma once

// ---------------------------------------------------------------------
// 構造体 (コンポーネント) 注釈
//
//   CCL_COMPONENT("DisplayName")
//   struct MyComponent { ... };
//
//   省略可能オプション:
//     CCL_COMPONENT("DisplayName", Tag1, Tag2, ...)
//     - "NoSerialize"  : シリアライズ対象外 (タグコンポーネントなど)
//     - "CustomGui"    : CustomGui を別ファイルで自作する
//     - "CustomSerialize" : Serialize/Deserialize を手書き特化する
// ---------------------------------------------------------------------
#define CCL_COMPONENT(...)


// ---------------------------------------------------------------------
// フィールド注釈 (自動型推論)
//
//   CCL_FIELD("Display Name", "Category")
//   float currentHP = 100.0f;
//
//   型は decltype で推論される。対応型:
//     float / int / bool / uint8_t / uint16_t / uint32_t /
//     XMFLOAT2 / XMFLOAT3 / XMFLOAT4 / std::string / EntityLink
// ---------------------------------------------------------------------
#define CCL_FIELD(...)


// ---------------------------------------------------------------------
// レンジ付きフィールド (ImGui で範囲制限したい場合)
//
//   CCL_FIELD_FLOAT_RANGED("Display", Speed, Min, Max, "Category")
//   CCL_FIELD_INT_RANGED("Display", Min, Max, "Category")
// ---------------------------------------------------------------------
#define CCL_FIELD_FLOAT_RANGED(...)
#define CCL_FIELD_INT_RANGED(...)


// ---------------------------------------------------------------------
// Enum フィールド
//
//   static const char* kMyEnumNames[] = { "Idle", "Run", "Attack" };
//
//   CCL_FIELD_ENUM_U8("State", kMyEnumNames, 3, "AI")
//   uint8_t state = 0;
// ---------------------------------------------------------------------
#define CCL_FIELD_ENUM_U8(...)
#define CCL_FIELD_ENUM_INT(...)


// ---------------------------------------------------------------------
// 旧 EntityID 形式 (移行期の互換用。新規には使わない)
// ---------------------------------------------------------------------
#define CCL_FIELD_ENTITY_ID(...)


// ---------------------------------------------------------------------
// マーカー注釈 (引数なし)
//
//   CCL_NO_SERIALIZE
//   bool isDirty = true;
//
//   → このフィールドはメタに含まれず、保存もインスペクタ表示もされない。
//      (デフォルトでアノテーション無しフィールドも対象外なので、
//       明示的に「シリアライズしないことを宣言する」用途で使う)
// ---------------------------------------------------------------------
#define CCL_NO_SERIALIZE