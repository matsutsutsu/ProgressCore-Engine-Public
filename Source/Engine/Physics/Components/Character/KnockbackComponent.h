#pragma once
// ===========================================================================
// 概要: 被弾時の吹き飛ばしと硬直の状態を持つ Component。
//       被弾させたいキャラ（プレイヤー・ボス等）に常に付けておく。
//
// 責務:
//   - 設定: 吹き飛ばす時間 duration と、操作を受け付けない硬直時間 stunDuration
//   - 実行時: 吹き飛ばしの速度と残り時間、硬直の残り時間
//
// 備考:
//   DamageResolutionSystem が命中時に書き、
//   JoltCharacterUpdateSystem が水平速度へ足しながらタイマーを減らす。
//   速度へ足して動かすので、壁や押し出しは物理が処理する（壁抜けしない）。
//
//   吹き飛ばす時間と硬直を分けるのは、
//   1つにすると「硬直を伸ばしたら吹き飛び過ぎる」ため。
//   被弾のたびに AddComponent しないのは、同時に多数が被弾しても
//   アーキタイプの移動を起こさないため。
// ===========================================================================
#include <SimpleMath.h>

struct KnockbackComponent
{
    // --- 設定（保存する）---

    float duration     = 0.18f; // 吹き飛ばす時間 [秒]。短いほど鋭く止まる
    float stunDuration = 0.35f; // 操作を受け付けない時間 [秒]。0 で硬直なし（読むのはプレイヤーだけ）

    // --- 実行時の値（保存しない）---

    DirectX::SimpleMath::Vector3 velocity  = {0.0f, 0.0f, 0.0f}; // 命中時の吹き飛ばしの速度 [m/s]
    float                        timer     = 0.0f;               // 吹き飛ばしの残り [秒]
    float                        stunTimer = 0.0f;               // 硬直の残り [秒]

    // 操作を受け付けない状態か
    bool IsStunned() const { return stunTimer > 0.0f; }
};
