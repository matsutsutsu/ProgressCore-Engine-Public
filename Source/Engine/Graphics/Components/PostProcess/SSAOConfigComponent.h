struct SSAOConfigComponent
{
    bool enable = true;

    // 半径 0.5m / 強さ 0.8 / バイアス 0.02 / 最大距離 50m
    GpuData::CbSSAOData data{0.5f, 0.8f, 0.02f, 50.0f};
};
