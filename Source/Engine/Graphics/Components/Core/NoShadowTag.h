//
// 責務:
//   - ShadowMapRenderSystem の走査対象から Entity を外す
//
// 備考: NoRenderTag は「描かない」、NoShadowTag は「描くが影を落とさない」。
//       カスケードシャドウはジオメトリを層の数（3回）ラスタライズするので、
//       影のコストは通常描画の約3倍になる。大量に出て1体の影がほぼ見えないもの
//       （ドローンなど）を外すと、見た目をほとんど変えずに描画負荷を下げられる。
//       どれを外すかは見た目の判断なので、コードの条件ではなくタグで決める。
//       除外は IfSystem の SetExclude<> で行うので、描画ループでの分岐は発生しない。
// ===========================================================================

