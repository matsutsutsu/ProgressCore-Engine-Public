// =====================================================================
// NoShadowTag
//   このタグが付いたエンティティは ShadowMapRenderSystem の
//   「走査対象そのもの」から外れる。通常描画には出るが、影を落とさない。
//
//   NoRenderTag との違い:
//     NoRenderTag = 見えない（当たり判定専用ジオメトリ）
//     NoShadowTag = 見えるが影は落とさない（描画コストの取捨選択）
//
//   なぜ必要か:
//     カスケードシャドウはジオメトリを3回ラスタライズするため、
//     影のコストは通常描画の3倍で効いてくる。
//     1000機のドローンのように「大量にあり、1体の影が絵にほぼ寄与しない」
//     ものを影から外すと、見た目をほとんど変えずに描画負荷が大きく落ちる。
//     どれを外すかは絵の判断なので、コード側の条件でなくタグで作者が決める。
//
//   実装メモ:
//     除外は IfSystem の SetExclude<> で行うため、描画ループ側に
//     毎フレームの分岐コストは一切発生しない。
// =====================================================================
struct NoShadowTag
{
};
