// =====================================================================
// NoRenderTag
//   このタグが付いたエンティティは、通常描画(ModelRenderSystem)と
//   シャドウ描画(ShadowMapRenderSystem)の「走査対象そのもの」から外れる。
//
//   用途:
//     当たり判定専用ジオメトリ（見えない壁/床/天井）。
//     例) 円形ステージの落下防止ドーナツに JoltMeshCollider を付け、
//         このタグで描画だけを消す。
//         → 「モデルを置いてから消す」ハックが不要になり、
//            1エンティティ・正確な形状のまま透明な当たり判定にできる。
//
//   実装メモ:
//     除外は IfSystem の SetExclude<> で行うため、描画ループ側に
//     毎フレームの分岐コストは一切発生しない。
//     VisibilityComponent.isVisible はフラスタムカリングが毎フレーム
//     上書きするので、恒久的な非表示には使えない（そのための本タグ）。
// =====================================================================
struct NoRenderTag {};
